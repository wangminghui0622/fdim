func NewGetIncrementalFriendsLogic(ctx context.Context, svcCtx *svc.ServiceContext) *GetIncrementalFriendsLogic {
	return &GetIncrementalFriendsLogic{
		ctx:    ctx,
		svcCtx: svcCtx,
		Logger: logx.WithContext(ctx),
	}
}

